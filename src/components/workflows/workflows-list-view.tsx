"use client";

import { useState, useEffect } from "react";
import Link from "next/link";

interface WorkflowItem {
  id: string;
  title: string;
  processTitle: string;
  status: string;
  version: number;
  stepsCount: number;
  target: string;
  created: string;
}

export function WorkflowsListView() {
  const [workflows, setWorkflows] = useState<WorkflowItem[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    fetch("/api/workflows")
      .then((res) => res.json())
      .then((data) => {
        if (data.workflows && Array.isArray(data.workflows)) {
          const mapped: WorkflowItem[] = data.workflows.map((wf: any) => {
            const steps = wf.workflow_json?.steps || [];
            const procTitle = wf.business_processes?.title || "Operational Process";
            const createdDate = wf.created_at
              ? new Date(wf.created_at).toLocaleDateString([], {
                  month: "short",
                  day: "numeric",
                })
              : "Recently";

            return {
              id: wf.id,
              title: wf.workflow_json?.trigger ? `${procTitle} Workflow` : "Operational Automation",
              processTitle: procTitle,
              status: wf.status || "draft",
              version: wf.version || 1,
              stepsCount: steps.length > 0 ? steps.length : 4,
              target: "My Trello board → Today & Telegram",
              created: createdDate,
            };
          });
          setWorkflows(mapped);
        }
      })
      .catch(() => {})
      .finally(() => setIsLoading(false));
  }, []);

  return (
    <div className="max-w-6xl mx-auto space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 dark:text-white tracking-tight">Automation Workflows</h1>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            Workflows generated by AI-Business-Automation requiring explicit human approval before execution.
          </p>
        </div>

        <Link
          href="/processes/new"
          className="inline-flex items-center gap-1.5 bg-slate-900 dark:bg-white text-white dark:text-slate-900 text-xs font-semibold px-4 py-2 rounded-lg hover:bg-slate-800 dark:hover:bg-slate-100 transition-colors shadow-sm self-start sm:self-auto"
        >
          <span>+</span>
          <span>Draft New Workflow</span>
        </Link>
      </div>

      <div className="bg-white dark:bg-slate-900 border border-slate-200/90 dark:border-slate-800 rounded-xl p-5 shadow-xs space-y-4 transition-colors">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-slate-100 dark:border-slate-800 text-slate-400 dark:text-slate-500 font-semibold uppercase tracking-wider text-[10px]">
                <th className="pb-3">Workflow Name</th>
                <th className="pb-3">Origin Process</th>
                <th className="pb-3">Status</th>
                <th className="pb-3">Steps</th>
                <th className="pb-3">Target Destination</th>
                <th className="pb-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
              {workflows.length > 0 ? (
                workflows.map((wf) => (
                  <tr key={wf.id} className="hover:bg-slate-50/60 dark:hover:bg-slate-800/60 transition-colors">
                    <td className="py-3.5 pr-2">
                      <span className="font-bold text-slate-900 dark:text-white block leading-tight">{wf.title}</span>
                      <span className="text-[11px] text-slate-400 dark:text-slate-500">v{wf.version} · {wf.created}</span>
                    </td>
                    <td className="py-3.5 text-slate-600 dark:text-slate-400 font-medium">{wf.processTitle}</td>
                    <td className="py-3.5">
                      {wf.status === "awaiting_approval" && (
                        <span className="bg-amber-50 dark:bg-amber-950/40 text-amber-800 dark:text-amber-300 border border-amber-200 dark:border-amber-800 text-[10px] font-semibold px-2 py-0.5 rounded-full">
                          Awaiting Approval
                        </span>
                      )}
                      {wf.status === "approved" && (
                        <span className="bg-slate-100 dark:bg-slate-800 text-slate-800 dark:text-white border border-slate-300 dark:border-slate-700 text-[10px] font-semibold px-2 py-0.5 rounded-full">
                          Approved
                        </span>
                      )}
                      {wf.status === "executed" && (
                        <span className="bg-slate-100 dark:bg-slate-800 text-slate-900 dark:text-slate-200 border border-slate-200 dark:border-slate-700 text-[10px] font-semibold px-2 py-0.5 rounded-full">
                          ✓ Executed
                        </span>
                      )}
                      {wf.status === "draft" && (
                        <span className="bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 text-[10px] font-semibold px-2 py-0.5 rounded-full">
                          Draft
                        </span>
                      )}
                      {wf.status === "rejected" && (
                        <span className="bg-slate-100 dark:bg-slate-800 text-slate-500 dark:text-slate-400 border border-slate-200 dark:border-slate-700 text-[10px] font-semibold px-2 py-0.5 rounded-full">
                          Rejected
                        </span>
                      )}
                    </td>
                    <td className="py-3.5 text-slate-700 dark:text-slate-300">{wf.stepsCount} steps</td>
                    <td className="py-3.5 text-slate-600 dark:text-slate-400 text-[11px]">{wf.target}</td>
                    <td className="py-3.5 text-right">
                      <Link
                        href={`/workflows/${wf.id}`}
                        className="text-xs font-semibold text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white bg-slate-50 dark:bg-slate-800 hover:bg-slate-100 dark:hover:bg-slate-700 px-2.5 py-1 rounded border border-slate-200 dark:border-slate-700 inline-flex items-center gap-1"
                      >
                        <span>Review</span>
                        <span>→</span>
                      </Link>
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={6} className="py-6 text-center text-slate-400 dark:text-slate-500 text-xs">
                    {isLoading ? "Loading workflows from Supabase..." : "No workflows found."}
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
